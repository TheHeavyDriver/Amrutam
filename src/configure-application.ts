import compress from '@fastify/compress';
import helmet from '@fastify/helmet';
import type { NestFastifyApplication } from '@nestjs/platform-fastify';
import { AppConfigService } from './config/app-config.service.js';
import { HEALTH_ROUTES } from './modules/health/health.routes.js';

export async function configureApplication(
  app: NestFastifyApplication,
  config: AppConfigService,
): Promise<void> {
  app.setGlobalPrefix(config.http.globalPrefix, { exclude: [...HEALTH_ROUTES] });

  app.enableCors({
    origin: config.http.corsOrigins.length > 0 ? config.http.corsOrigins : false,
    credentials: true,
    methods: ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS'],
    allowedHeaders: [
      'Authorization',
      'Content-Type',
      'Idempotency-Key',
      'X-Request-Id',
      'If-None-Match',
    ],
    exposedHeaders: [
      'X-Request-Id',
      'RateLimit-Limit',
      'RateLimit-Remaining',
      'RateLimit-Reset',
      'Retry-After',
    ],
    maxAge: 86_400,
  });

  await app.register(helmet);
  await app.register(compress, { global: true, threshold: 1024 });

  const fastify = app.getHttpAdapter().getInstance();

  // Request ids are generated by Fastify (see createFastifyAdapter), so this
  // hook guarantees every response — including 404s — echoes the correlation id.
  fastify.addHook('onSend', (request, reply, payload, done) => {
    void reply.header('x-request-id', request.id);
    done(null, payload);
  });
}
